const CATEGORY_LABELS: Record<GlossaryTerm['category'], string> = {
  tactics: 'Scam tactic',
  payment: 'Payment method',
  security: 'Account security',
  tech: 'Technology',
};

export function Words() {
  const [query, setQuery] = useState('');

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return GLOSSARY_TERMS;
    return GLOSSARY_TERMS.filter(
      (t) =>
        t.term.toLowerCase().includes(q) ||
        t.definition.toLowerCase().includes(q) ||
        t.example.toLowerCase().includes(q) ||
        CATEGORY_LABELS[t.category].toLowerCase().includes(q)
    );
  }, [query]);

  return (
    <article className="section words-page" aria-labelledby="words-title">
      <nav className="breadcrumbs no-print" aria-label="Breadcrumb" style={{ marginBottom: '16px' }}>
        <a href="#/learn" className="back-link">
          <Icon name="arrowLeft" />
          <span>Back to Lessons</span>
        </a>
      </nav>

      <header className="page-head torn-bottom">
        <h1 id="words-title">Scam words in plain English</h1>
        <p className="lede">
          Scam terminology is full of confusing jargon. Here is what all the buzzwords actually mean, with plain-English definitions and real examples.
        </p>
      </header>

      {/* Search and filter bar */}
      <div className="words-search-bar" style={{ margin: '24px 0 20px 0' }}>
        <label htmlFor="words-search-input" className="stack-label" style={{ marginBottom: '8px' }}>
          Search vocabulary
        </label>
        <div className="search-input-wrapper">
          <input
            id="words-search-input"
            type="search"
            className="words-search-input"
            placeholder="Type a word (e.g. phishing, gift card, 2FA)..."
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            aria-label="Search glossary terms"
          />
          {query && (
            <button
              type="button"
              className="btn btn-secondary words-clear-btn"
              onClick={() => setQuery('')}
              aria-label="Clear search input"
            >
              Clear
            </button>
          )}
        </div>
        <p className="search-status" aria-live="polite" style={{ fontSize: '20px', color: 'var(--ink-secondary)', marginTop: '8px' }}>
          Showing {filtered.length} of {GLOSSARY_TERMS.length} terms
        </p>
      </div>

      {filtered.length === 0 ? (
        <div className="panel" style={{ padding: '32px', textAlign: 'center' }}>
          <p style={{ fontSize: '18px', fontWeight: 600, color: 'var(--ink)' }}>No terms matched "{query}"</p>
          <p style={{ color: 'var(--ink-secondary)' }}>Try searching for a simpler word like "card", "code", or "call".</p>
          <button type="button" className="btn btn-primary" onClick={() => setQuery('')} style={{ marginTop: '12px' }}>
            Show all terms
          </button>
        </div>
      ) : (
        <div className="words-list" role="list">
          {filtered.map((item) => (
            <article key={item.id} className="panel word-card" role="listitem">
              <div className="word-card-header">
                <h2 style={{ fontSize: '22px', margin: 0, color: 'var(--navy)' }}>{item.term}</h2>
                <span className="word-category-badge">{CATEGORY_LABELS[item.category]}</span>
              </div>
              <p className="word-definition" style={{ fontSize: '20px', lineHeight: 1.5, margin: '12px 0 16px 0', color: 'var(--ink)' }}>
                {item.definition}
              </p>
              <div className="word-example-box">
                <span className="example-label">Real-world example</span>
                <p style={{ margin: '4px 0 0 0', fontSize: '20px', color: 'var(--ink-secondary)' }}>{item.example}</p>
              </div>
            </article>
          ))}
        </div>
      )}
    </article>
  );
}
