// Run with `npm run audio:list`. Prints every call recording the app expects,
// with the line it should say, and writes the same list to vault/03-Content/Audio-Needed.md.
import { writeFileSync } from 'node:fs';
import { audioNeeded } from '../src/engine/validate.ts';
import { readContent } from './read-content.ts';

const { scenarios, audioFiles } = readContent();
const needed = audioNeeded(scenarios);
const done = needed.filter((a) => audioFiles.includes(a.file)).length;

const lines = needed.map((a) => `- [${audioFiles.includes(a.file) ? 'x' : ' '}] \`${a.file}\` — "${a.transcript}"`);
for (const line of lines) console.log(line);
console.log(`\n${done} of ${needed.length} recordings are in public/audio.`);

const markdown = `---
type: content
updated: ${new Date().toISOString().slice(0, 10)}
---
# Audio needed (generated by \`npm run audio:list\`; don't edit by hand)

Put each MP3 in \`app/public/audio/\` with exactly this file name. [x] = file is there.
${done} of ${needed.length} done. Until a file is added, the app shows the transcript and "Recording not added yet".

${lines.join('\n')}
`;
writeFileSync(new URL('../../vault/03-Content/Audio-Needed.md', import.meta.url), markdown);
console.log('Wrote vault/03-Content/Audio-Needed.md');
